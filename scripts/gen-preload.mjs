// Writes the <link rel="modulepreload"> list in index.html: every module the first screen needs (the static import graph of
// src/main.js), so the browser fetches them all at once instead of discovering them level by level (import -> fetch -> parse -> next import).
// There is no bundler, so this is the cheap way to flatten the waterfall.   node scripts/gen-preload.mjs          rewrite index.html
//                                                                          node scripts/gen-preload.mjs --check  exit 1 when the list is stale
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const START = "<!-- modulepreload:start (generated by scripts/gen-preload.mjs) -->";
const END = "<!-- modulepreload:end -->";

function staticImports(file) {
  const src = readFileSync(file, "utf8");
  const out = [];
  // `import ... from "x"`, `import "x"`, `export ... from "x"` -- not the dynamic import("x") calls (those are the lazy pages)
  for (const m of src.matchAll(/^\s*(?:import|export)\s[^'"`;]*?(?:from\s*)?["'](\.[^"']+)["']/gm)) out.push(m[1]);
  return out.map((p) => resolve(dirname(file), p));
}

const html0 = readFileSync(resolve(root, "index.html"), "utf8");
const seen = new Set();
const order = [];
(function walk(file) {
  if (seen.has(file)) return;
  seen.add(file);
  for (const dep of staticImports(file)) walk(dep);
  order.push(file);
})(resolve(root, "src/main.js"));

const vendor = [...JSON.parse(html0.match(/<script type="importmap">([\s\S]*?)<\/script>/)[1]).imports ? Object.values(JSON.parse(html0.match(/<script type="importmap">([\s\S]*?)<\/script>/)[1]).imports) : []].map((h) => `<link rel="modulepreload" href="${h}" />`);
const links = [...vendor, ...order.reverse().map((f) => `<link rel="modulepreload" href="./${relative(root, f)}" />`)];
const block = `${START}\n${links.join("\n")}\n${END}`;
const htmlPath = resolve(root, "index.html");
const html = readFileSync(htmlPath, "utf8");
let next;
if (html.includes(START)) next = html.replace(new RegExp(`${START.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}[\\s\\S]*?${END}`), block);
else next = html.replace('<script defer src="./vendor/supabase.umd.js"></script>', `${block}\n<script defer src="./vendor/supabase.umd.js"></script>`);
if (process.argv.includes("--check")) {
  if (next !== html) { console.error("index.html modulepreload list is stale: run node scripts/gen-preload.mjs"); process.exit(1); }
  console.log(`modulepreload list is current (${links.length} modules)`);
} else {
  writeFileSync(htmlPath, next);
  console.log(`index.html: ${links.length} modules listed`);
}
