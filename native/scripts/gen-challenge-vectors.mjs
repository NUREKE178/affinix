// Writes composeApp/src/commonTest/kotlin/space/affinix/app/ChallengeVectors.kt: Taste Match links made (and refused) by the WEBSITE's code
// (src/lib/arena/challenge.js), so the Kotlin port in store/Challenge.kt can be tested against them. CI regenerates the file and fails on any
// difference, so a change on either side that breaks the links between the two apps cannot go unnoticed.   node native/scripts/gen-challenge-vectors.mjs
import { writeFileSync } from "node:fs";
import { planRound } from "../../src/lib/arena/sampler.js";
import { mulberry32 } from "../../src/lib/prng.js";
import { encodeEntry } from "../../src/lib/arena/ledger.js";
import { encodeChallenge, decodeChallenge } from "../../src/lib/arena/challenge.js";

const SEASON = "202611";

/** n shareable answers (no eye tests) from the sampler, with a mixed pattern of picks */
function sample(n, seed) {
  const out = [];
  for (let k = 0; out.length < n && k < 30; k++) {
    for (const d of planRound({ season: SEASON, rand: mulberry32(seed + k), size: 10, seen: new Set(), recent: [], focus: {}, day: "2026-11-08", drops: true, exposure: null })) {
      if (!d.objective && out.length < n && !out.some((x) => x.family === d.family && x.a === d.a && x.b === d.b)) out.push({ family: d.family, a: d.a, b: d.b, dim: d.dim, pick: (out.length * 3 + seed) % 2 });
    }
  }
  return out;
}
const summary = (answers) => answers.map((a) => `${a.family}:${a.a}:${a.b}:${a.dim}:${a.pick}`).join(",");
const kt = (s) => JSON.stringify(s).replace(/\$/g, "\\$");

const cases = [
  { note: "ten answers, a surname is dropped", name: "Aigerim Seriqqyzy", answers: sample(10, 3) },
  { note: "Cyrillic name, eight answers", name: "Айгерим Сериккызы", answers: sample(8, 11) },
  { note: "two emoji (surrogate pairs) as a name", name: "😀😀 Ali", answers: sample(7, 21) },
  { note: "no name", name: "", answers: sample(6, 5) },
  { note: "the smallest link, five answers", name: "Nurlan", answers: sample(5, 8) },
];
const good = cases.map((c) => {
  const text = encodeChallenge({ season: SEASON, answers: c.answers, name: c.name });
  const back = decodeChallenge(text);
  if (!back || summary(back.answers) !== summary(c.answers)) throw new Error("the website cannot read its own link: " + c.note);
  return { text, season: back.season, name: back.name, answers: summary(back.answers), note: c.note };
});

// links the website refuses (see tests/challenge.test.js); the Kotlin port must refuse every one of them too
const base = sample(8, 3);
const entries = base.map((a) => encodeEntry(a.family, a.a, a.b, a.dim, a.pick));
const link = (season, list, name = "") => `1.${season}.${list.map((e) => e.toString(36)).join("-")}.${name}`;
const goodText = link(SEASON, entries);
const bad = [
  ["empty", ""],
  ["another version", goodText.replace(/^1\./, "2.")],
  ["month 13", link("202613", entries)],
  ["short season", link("20261", entries)],
  ["four entries", link(SEASON, entries.slice(0, 4))],
  ["eleven entries", link(SEASON, [...entries, ...entries].slice(0, 11))],
  ["five parts", goodText + "x"],
  ["wrong separator", goodText.replace(/-/g, "+")],
  ["an entry above the largest ledger value", `1.${SEASON}.zzzzzz-1-2-3-4.`],
  ["the same duel twice", link(SEASON, [...entries.slice(0, 7), entries[0]])],
  ["the lower index after the higher", link(SEASON, [...entries.slice(0, 7), encodeEntry("mark", 9, 3, "premium", 0)])],
  ["an eye test", link(SEASON, [encodeEntry(base[0].family, base[0].a, base[0].b, "clarity", 0), ...entries.slice(1)])],
  ["a character that is not URL-safe", goodText.slice(0, -1) + "!"],
  ["a name that is not base64", `1.${SEASON}.${entries.join("-").replace(/\d+/g, (m) => Number(m).toString(36))}.@@@@`],
  ["far too long", "x".repeat(500)],
].map(([note, text]) => {
  if (decodeChallenge(text) !== null) throw new Error("the website accepts a link it should refuse: " + note);
  return { note, text };
});

const out = `package space.affinix.app

// GENERATED by native/scripts/gen-challenge-vectors.mjs from the website's src/lib/arena/challenge.js. Do not edit: CI regenerates it and fails on any difference.

/** Taste Match links made and refused by the website's code; ChallengeTest checks the Kotlin port against them. */
object ChallengeVectors {
    /** [answers]: "family:a:b:dim:pick,..." in order */
    class Good(val note: String, val text: String, val season: String, val name: String?, val answers: String)

    val good = listOf(
${good.map((g) => `        Good(${kt(g.note)}, ${kt(g.text)}, ${kt(g.season)}, ${g.name === null ? "null" : kt(g.name)}, ${kt(g.answers)}),`).join("\n")}
    )

    /** [note] to [text]: every one of them must be refused */
    val bad = listOf(
${bad.map((b) => `        ${kt(b.note)} to ${kt(b.text)},`).join("\n")}
    )
}
`;
writeFileSync(new URL("../composeApp/src/commonTest/kotlin/space/affinix/app/ChallengeVectors.kt", import.meta.url), out);
console.log(`ok: ${good.length} links the website makes, ${bad.length} it refuses`);
