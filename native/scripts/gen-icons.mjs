// Generates composeApp/src/commonMain/kotlin/space/affinix/app/ui/IconData.kt from the website's hand-built icon set (src/components/icons.js), so the apps use the same
// glyphs. rect / circle elements are turned into path data. Run from the repo root:  node native/scripts/gen-icons.mjs
import { readFileSync, writeFileSync } from "node:fs";

const src = readFileSync(new URL("../../src/components/icons.js", import.meta.url), "utf8");
const lines = src.split("\n").filter((l) => /^  \w+: html`.*`,\s*$/.test(l));
const num = (v) => (v === undefined ? 0 : Number(v));
const f = (n) => String(Math.round(n * 1000) / 1000);

function rectPath(a) {
  const x = num(a.x), y = num(a.y), w = num(a.width), h = num(a.height);
  const r = Math.min(num(a.rx ?? a.ry), w / 2, h / 2);
  if (!r) return `M${f(x)} ${f(y)}h${f(w)}v${f(h)}h${f(-w)}z`;
  return `M${f(x + r)} ${f(y)}h${f(w - 2 * r)}a${f(r)} ${f(r)} 0 0 1 ${f(r)} ${f(r)}v${f(h - 2 * r)}a${f(r)} ${f(r)} 0 0 1 ${f(-r)} ${f(r)}h${f(-(w - 2 * r))}a${f(r)} ${f(r)} 0 0 1 ${f(-r)} ${f(-r)}v${f(-(h - 2 * r))}a${f(r)} ${f(r)} 0 0 1 ${f(r)} ${f(-r)}z`;
}
const circlePath = (a) => { const cx = num(a.cx), cy = num(a.cy), r = num(a.r); return `M${f(cx - r)} ${f(cy)}a${f(r)} ${f(r)} 0 1 0 ${f(2 * r)} 0a${f(r)} ${f(r)} 0 1 0 ${f(-2 * r)} 0z`; };

const out = [];
for (const line of lines) {
  const name = line.match(/^  (\w+):/)[1];
  const body = line.slice(line.indexOf("`") + 1, line.lastIndexOf("`"));
  const shapes = [];
  for (const m of body.matchAll(/<(path|rect|circle)\b([^>]*?)\/>/g)) {
    const attrs = Object.fromEntries([...m[2].matchAll(/([\w-]+)="([^"]*)"/g)].map((x) => [x[1], x[2]]));
    const cls = attrs.class ?? "";
    const d = m[1] === "path" ? attrs.d : m[1] === "rect" ? rectPath(attrs) : circlePath(attrs);
    if (!d) continue;
    const solid = cls === "f" || (attrs.fill === "currentColor" && attrs.stroke === "none");
    const tint = cls === "b" || cls === "t";
    const stroke = !solid && cls !== "t";
    shapes.push({ d, fill: solid ? 2 : tint ? 1 : 0, stroke, w: attrs["stroke-width"] ? Number(attrs["stroke-width"]) : 2, eo: attrs["fill-rule"] === "evenodd" });
  }
  out.push({ name, shapes });
}
const lit = (s) => '"' + s.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\$/g, "\\$") + '"';
let kt = `// GENERATED by native/scripts/gen-icons.mjs from src/components/icons.js. Do not edit by hand.\npackage space.affinix.app.ui\n\n`;
kt += `/** fill: 0 none, 1 tint (20 %; solid when the icon is "filled"), 2 solid */\ninternal class IcShape(val d: String, val fill: Int, val stroke: Boolean, val width: Float, val evenOdd: Boolean)\n\n`;
kt += `internal val ICONS: Map<String, List<IcShape>> = mapOf(\n`;
for (const { name, shapes } of out) {
  kt += `    ${lit(name)} to listOf(\n` + shapes.map((s) => `        IcShape(${lit(s.d)}, ${s.fill}, ${s.stroke}, ${s.w}f, ${s.eo}),`).join("\n") + `\n    ),\n`;
}
kt += `)\n`;
writeFileSync(new URL("../composeApp/src/commonMain/kotlin/space/affinix/app/ui/IconData.kt", import.meta.url), kt);
console.log(`ok: ${out.length} icons, ${out.reduce((n, o) => n + o.shapes.length, 0)} shapes`);
